import { createHash } from 'node:crypto'
import { copyFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, relative, sep } from 'node:path'
import process from 'node:process'
import { fileURLToPath, URL } from 'node:url'

import { defineConfig, searchForWorkspaceRoot, type Plugin } from 'vite'
import tailwindcss from '@tailwindcss/vite'
import vue from '@vitejs/plugin-vue'
import vueJsx from '@vitejs/plugin-vue-jsx'
import vueDevTools from 'vite-plugin-vue-devtools'

// The pdfrs repo, sibling of this one: "pdfrs-editor" is linked from
// ../pdfrs/packages/pdfrs-editor, and through it the wasm package from
// ../pdfrs/pkg-npm.
const pdfrsRepo = fileURLToPath(new URL('../pdfrs', import.meta.url))

/**
 * The website's address, ending in /: canonical link, Open Graph tags,
 * sitemap. The GitHub Pages workflow sets SITE_URL to the Pages address.
 */
const siteUrl = `${(process.env.SITE_URL || 'https://teo666.github.io/pdfrs-app/').replace(/\/+$/, '')}/`

/**
 * What the website wants and the browser extension doesn't:
 * - `%SITE_URL%` in index.html becomes the site's address; in the extension
 *   the block between `<!-- seo` and `<!-- /seo -->` is dropped instead;
 * - next to the built index.html: robots.txt, sitemap.xml, 404.html (a
 *   copy of index.html, which GitHub Pages serves for any other path - the
 *   router sends it back to the editor), and sw.js, the service worker that
 *   keeps the whole app, wasm included, so it opens without a network (see
 *   src/serviceWorker.ts).
 */
function website(): Plugin {
  let extension = false
  return {
    name: 'pdfrs:website',
    configResolved(config) {
      extension = config.mode === 'extension'
    },
    transformIndexHtml: (html) =>
      extension
        ? html.replace(/\s*<!--\s*seo[\s\S]*?<!-- \/seo -->/, '')
        : html.replaceAll('%SITE_URL%', siteUrl),
    writeBundle(options) {
      if (extension || !options.dir) return
      const out = options.dir
      copyFileSync(join(out, 'index.html'), join(out, '404.html'))
      writeFileSync(join(out, 'robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${siteUrl}sitemap.xml\n`)
      writeServiceWorker(out)
      writeFileSync(
        join(out, 'sitemap.xml'),
        `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <url>
    <loc>${siteUrl}</loc>
    <lastmod>${new Date().toISOString().slice(0, 10)}</lastmod>
  </url>
</urlset>
`,
      )
    },
  }
}

/** Files of the built site the app doesn't need to run, left out of the offline copy. */
const notForOffline = new Set(['404.html', 'robots.txt', 'sitemap.xml', 'og-image.png', 'sw.js'])

/**
 * The service worker, with the list of the build's files in it. Its cache's
 * name comes from that list, so a new build (new hashed file names) installs
 * as a new worker, which fills a new cache and drops the old one.
 */
function writeServiceWorker(out: string) {
  const files = readdirSync(out, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => relative(out, join(entry.parentPath, entry.name)).split(sep).join('/'))
    .filter((file) => !notForOffline.has(file))
    .sort()
  const version = createHash('sha256').update(files.join('\n')).digest('hex').slice(0, 12)
  // Paths relative to sw.js, which sits at the site's root: "./" is the page itself.
  const urls = ['./', ...files.filter((file) => file !== 'index.html').map((file) => `./${file}`)]
  writeFileSync(
    join(out, 'sw.js'),
    `// Generated by vite.config.ts (writeServiceWorker): the app, kept for offline use.
const CACHE = 'pdfrs-${version}'
const FILES = ${JSON.stringify(urls, null, 2)}

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()))
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith('pdfrs-') && key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('fetch', (event) => {
  const request = event.request
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return
  if (request.mode === 'navigate') {
    // The page from the network when there is one (a new version shows at
    // once), the kept one otherwise.
    event.respondWith(fetch(request).catch(() => caches.match('./', { cacheName: CACHE, ignoreVary: true })))
    return
  }
  // Everything else has a hashed name, or doesn't change: the kept copy first.
  // ignoreVary: a server's "Vary: Origin" would otherwise keep the module
  // scripts (requested with an Origin) from matching what was kept.
  event.respondWith(caches.match(request, { cacheName: CACHE, ignoreVary: true }).then((kept) => kept || fetch(request)))
})
`,
  )
}

// https://vite.dev/config/
export default defineConfig({
  plugins: [vue(), vueJsx(), vueDevTools(), tailwindcss(), website()],
  resolve: {
    alias: {
      '@': fileURLToPath(new URL('./src', import.meta.url)),
    },
  },
  server: {
    // Linked packages outside this project are served as source (never
    // pre-bundled, so a wasm-pack rebuild shows up without clearing any
    // cache), but the dev server's file-system guard must allow them.
    fs: {
      allow: [searchForWorkspaceRoot(process.cwd()), pdfrsRepo],
    },
  },
})
